"""파트 간 인터페이스(Protocol). P1/P3/P4 없이 mock 으로 개발한다."""
from typing import Optional, Protocol


class PostureEngineLike(Protocol):          # P1
    def start(self): ...
    def pause(self): ...
    def resume(self): ...
    def stop(self): ...
    def get_state(self) -> dict: ...
    def begin_calibration(self) -> dict: ...
    def preview_calibration(self) -> dict: ...
    def confirm_calibration(self) -> dict: ...
    def get_calibration(self) -> Optional[dict]: ...
    def on_event(self, callback): ...
    def set_debug(self, enabled: bool): ...
    def update_runtime_settings(self, **kw): ...
    def get_health(self) -> dict: ...       # {"camera": ready|error|unavailable, "pose": ...}


class SpeakClientLike(Protocol):            # P3
    def speak(self, text: str, kind: str, volume: int): ...
    def warmup(self, texts: list): ...
    def set_mic(self, enabled: bool): ...
    def state(self) -> dict: ...            # {"stt": ..., "tts": ...}


class LLMClientLike(Protocol):              # P4 LLM 서버
    def complete(self, utterance: str) -> str: ...
    def health(self) -> str: ...


class CommandProcessorLike(Protocol):       # P4 command 라이브러리
    def process(self, raw: str, services, *, utterance: Optional[str] = None, options=None) -> dict:
        """-> {"code", "result", "tts_text", "pending"(선택: {"type":"body_part|intent|time"})}"""


class ServiceHandles(Protocol):             # P4 실행기에 주입(Hub 가 구현)
    def get_posture(self): ...
    def monitoring_start(self): ...
    def monitoring_pause(self): ...
    def monitoring_stop(self): ...
    def get_session(self): ...
    def get_last_session(self): ...
    def set_break_alarm(self, minutes: int): ...
    def get_break_status(self): ...
    def get_stretch_guide(self, part: str): ...
    def get_setting(self, key: str): ...
